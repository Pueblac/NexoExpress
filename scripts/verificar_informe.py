"""Verifica un informe: el borrador Markdown y el .docx que salió de él (kit coordinador v1.6.0).

Lo corre quien renderizó el informe, antes de entregarlo, y lo vuelve a correr el Agente C en su compuerta
(o el Verificador, si el informe pasa por él). Mide en disco; lo que diga el informe de sí mismo no cuenta.

Sobre el BORRADOR:
  D4  solo Markdown que el renderizador entiende: ni viñetas o citas partidas en dos líneas físicas, ni
      enlaces, notas al pie, HTML o diagramas embebidos (salen literales o rotos en el .docx);
  D1  sin huella: ni herramientas de asistencia ni el método interno (sección `informes.huella`).
Sobre el .DOCX (en `informes.dir_informes`, con el nombre del borrador o el de --salida):
  vigente      su identificador es la huella del borrador actual (lo estampa renderizar_informe.py);
  marcadores   no queda ninguno de `informes.marcadores` sin reemplazar, ni en encabezados y pies;
  títulos      los del borrador están todos, en orden y con su nivel;
  tablas       las del borrador están todas, con sus filas y columnas;
  imágenes     las del borrador están todas y ninguna salió como «Imagen no encontrada»;
  D1           sin huella en el texto ni en las propiedades del documento.

La huella se mide con control positivo: en la misma corrida se comprueba que el patrón detecta muestras con
huella y respeta muestras limpias; si no, el resultado no vale (exit 2). Un «cero coincidencias» sin ese
control no prueba nada.

Origen: los `verificar_docx_*.py` y `revisar_huella_remota.py --archivo` del Coordinador de Indicadores
I+D 2026, que verificaron así cada capítulo de su memoria técnica.

KIT COORDINADOR — no hay rutas absolutas: el workspace sale de la ubicación del script.

Uso:
    python -I scripts/verificar_informe.py docs/borradores/x.md [--salida Informe_X.docx]
    python -I scripts/verificar_informe.py docs/borradores/x.md --solo-borrador     # antes de renderizar
    # exit 0 = CONFORME; 1 = NO CONFORME (cada falla con su línea); 2 = uso, configuración o medidor roto
"""

import argparse
import importlib.util
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_spec = importlib.util.spec_from_file_location("renderizar_informe", Path(__file__).with_name("renderizar_informe.py"))
R = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(R)

# Herramientas de asistencia: los nombres del hook commit-msg que tienen sentido en un documento (no «llama» ni
# «ai», que en castellano son palabras corrientes), más lo que dejan los motores en un texto.
TERMINOS_POR_DEFECTO = [
    "IA", "inteligencia artificial", "modelos? de lenguaje", "LLMs?", "agentes?", "subagentes?", "prompts?",
    "Claude", "Anthropic", "Sonnet", "Opus", "Fable", "Haiku", "Gemini", "Antigravity", "agy", "ChatGPT", "GPT-?\\d*",
    "OpenAI", "Copilot", "Mistral", "DeepSeek", "Perplexity", "Grok", "Qwen", "Co-Authored-By",
    "generado por IA", "generated by", "CLAUDE\\.md", "\\.agents", "\\.claude",
]
# Método interno del kit: lo que delata la cadena de roles aunque no nombre ninguna herramienta.
# Distinguen mayúsculas (como los roles: «el Arquitecto» es huella, «un arquitecto» no); `(?i:…)` para lo contrario.
METODO_POR_DEFECTO = [
    "Agente C", "(?i:[óo]rden(?:es)? de ingenier[íi]a)", "(?i:fichas? de encuadre)", "(?i:arranques? en fr[íi]o)",
    "Plan de actividades", "(?i:decisi[óo]n delegada)", "DECISION_DELEGADA", "(?i:sello de rol)",
]
# Cargos que en un informe son institucionales, no huella del método.
PERMITIDOS_POR_DEFECTO = ["Director", "Coordinador"]
MUESTRAS_LIMPIAS = ["un verificador que no compara", "el día de la entrega", "se llama así",
                    "directorio de salida", "la agencia de calidad", "el ingeniero de la empresa",
                    "media de la serie", "correspondencia validada"]


def patrones_de_huella(cfg):
    """Devuelve (literal, metodo, muestras_con_huella) o None si la huella está desactivada."""
    h = cfg["_huella_cfg"]
    if h.get("activa") is False:
        return None
    terminos = h.get("terminos") or TERMINOS_POR_DEFECTO
    terminos = list(terminos) + list(h.get("terminos_extra") or [])
    permitidos = set(h.get("permitidos") or PERMITIDOS_POR_DEFECTO)
    roles = sorted({r.capitalize() for r in cfg["_roles"] if r != "coordinador"} - permitidos)
    metodo = list(h.get("metodo") or METODO_POR_DEFECTO) + list(h.get("metodo_extra") or [])
    literal = re.compile(r"(?<![\w.])(?:" + "|".join(terminos) + r")(?![\w])", re.I)
    partes = [f"(?:{m})" for m in metodo]
    if roles:
        partes.append(r"\b(?:" + "|".join(map(re.escape, roles)) + r")(?![\w])")   # con mayúscula: «el Arquitecto»
    metodo_re = re.compile(r"(?<![\w])(?:" + "|".join(partes) + r")") if partes else None
    muestras = ["redactado con Claude Sonnet", "lo hizo un agente", "Co-Authored-By"]
    muestras += [f"el {r} decidió" for r in roles[:3]]
    return literal, metodo_re, muestras


def control_positivo(pat):
    literal, metodo, muestras = pat
    def casa(t):
        return bool(literal.search(t) or (metodo and metodo.search(t)))
    fallan = [t for t in muestras if not casa(t)]
    falsos = [t for t in MUESTRAS_LIMPIAS if casa(t)]
    return fallan, falsos


def buscar_huella(pat, lineas):
    literal, metodo, _ = pat
    hits = []
    for n, linea in enumerate(lineas, 1):
        encontrados = [m.group(0) for m in literal.finditer(linea)]
        if metodo:
            encontrados += [m.group(0) for m in metodo.finditer(linea)]
        if encontrados:
            hits.append((n, ", ".join(dict.fromkeys(encontrados)), linea.strip()))
    return hits


# ---------------------------------------------------------------- estructura esperada del borrador

def estructura_del_borrador(lineas):
    titulos, tablas, imagenes = [], [], 0
    i, en_codigo = 0, False
    while i < len(lineas):
        limpia = lineas[i].strip()
        if limpia.startswith("```"):
            en_codigo = not en_codigo
            i += 1
            continue
        if en_codigo:
            i += 1
            continue
        if limpia.startswith("|"):
            filas = []
            while i < len(lineas) and lineas[i].strip().startswith("|"):
                celdas = [c.strip() for c in lineas[i].strip().strip("|").split("|")]
                if not all(re.fullmatch(r":?-{3,}:?", c) for c in celdas):
                    filas.append(len(celdas))
                i += 1
            if filas:
                tablas.append((len(filas), max(filas)))
            continue
        if re.fullmatch(r"!\[(.*?)\]\((.+?)\)", limpia):
            imagenes += 1
        else:
            m = re.match(r"(#{1,4})\s+(.*)", limpia)
            if m:
                titulos.append((len(m.group(1)), m.group(2).strip()))
        i += 1
    return titulos, tablas, imagenes


def nivel_de_titulo(p):
    m = re.match(r"(?:Heading|T[íi]tulo)\s*(\d)", p.style.name if p.style is not None else "")
    return int(m.group(1)) if m else None


def es_sufijo(esperado, real):
    return len(real) >= len(esperado) and real[len(real) - len(esperado):] == esperado


# ---------------------------------------------------------------- principal

def main(argv=None):
    ap = argparse.ArgumentParser(description="Verifica un borrador de informe y el .docx que salió de él.")
    ap.add_argument("markdown")
    ap.add_argument("--salida", help="nombre del .docx si no es el del borrador")
    ap.add_argument("--solo-borrador", action="store_true", help="solo D4 y D1 sobre el borrador")
    args = ap.parse_args(argv)

    try:
        cfg, _ = R.cargar_config()
    except R.ErrorDeConfiguracion as e:
        print(e)
        return 2
    ruta_md = R.ruta_del_proyecto(args.markdown)
    if not ruta_md.exists():
        print(f"STOP: no existe el borrador {ruta_md}")
        return 2
    lineas = ruta_md.read_text(encoding="utf-8").splitlines()
    fallas = 0

    def check(nombre, ok, detalle="", items=()):
        nonlocal fallas
        print(f"[{'OK ' if ok else 'FALLA'}] {nombre}" + (f" -- {detalle}" if detalle else ""))
        for it in list(items)[:40]:
            print(f"        {it}")
        if not ok:
            fallas += 1

    print(f"Borrador: {ruta_md} ({R.huella_borrador(ruta_md)})")

    pat = patrones_de_huella(cfg)
    if pat:
        fallan, falsos = control_positivo(pat)
        if fallan or falsos:
            print(f"STOP: el medidor de huella no vale. No detecta: {fallan}; marca como huella: {falsos}. "
                  "Revisa informes.huella en coordinador.json.")
            return 2
        print(f"Control positivo del medidor: {len(pat[2])} muestras con huella detectadas, "
              f"{len(MUESTRAS_LIMPIAS)} limpias respetadas -> OK")
    else:
        print("AVISO: informes.huella.activa = false; no se mide la huella.")

    d4 = R.revisar_markdown(lineas)
    check("D4 borrador: solo Markdown que el renderizador entiende", not d4, f"casos={len(d4)}",
          [f"línea {n}: {q}" for n, q in d4])
    if pat:
        hb = buscar_huella(pat, lineas)
        check("D1 borrador: sin huella de herramientas ni de método", not hb, f"líneas={len(hb)}",
              [f"línea {n}: «{t}» en: {s[:100]}" for n, t, s in hb])

    if not args.solo_borrador:
        if R.Document is None:
            print("STOP: falta python-docx. Instálalo con: python -m pip install python-docx")
            return 2
        ruta_docx = R.ruta_del_proyecto(cfg["dir_informes"]) / (args.salida or f"{ruta_md.stem}.docx")
        if not ruta_docx.exists():
            check("docx existe", False, f"no está {ruta_docx}; renderiza con scripts/renderizar_informe.py")
        else:
            print(f"Documento: {ruta_docx}")
            doc = R.Document(str(ruta_docx))
            sello = R.huella_borrador(ruta_md)
            ident = doc.core_properties.identifier or "(sin identificador)"
            check("vigente: el .docx salió del borrador actual", ident == sello,
                  f"docx={ident} borrador={sello}" + ("" if ident == sello else "; vuelve a renderizar"))

            textos = [p.text for p in R.parrafos_de_plantilla(doc)]
            sin_reemplazar = sorted({k for k in cfg["marcadores"] for t in textos if k in t})
            check("marcadores de la plantilla reemplazados", not sin_reemplazar,
                  f"quedan={sin_reemplazar}" if sin_reemplazar else f"{len(cfg['marcadores'])} marcador(es) declarados")

            titulos_md, tablas_md, imagenes_md = estructura_del_borrador(lineas)
            titulos_doc = [(nivel_de_titulo(p), p.text.strip()) for p in doc.paragraphs
                           if nivel_de_titulo(p) and p.text.strip()]
            ok_t = es_sufijo(titulos_md, titulos_doc)
            faltan = [f"H{n} {t}" for n, t in titulos_md if (n, t) not in titulos_doc]
            check("títulos del borrador, en orden y con su nivel", ok_t,
                  f"{len(titulos_md)} esperados, {len(titulos_doc)} en el documento",
                  [f"falta o cambió: {f}" for f in faltan] if not ok_t else ())

            tablas_doc = [(len(t.rows), len(t.columns)) for t in doc.tables]
            check("tablas del borrador con sus filas y columnas", es_sufijo(tablas_md, tablas_doc),
                  f"esperadas={tablas_md} documento={tablas_doc[-len(tablas_md):] if tablas_md else tablas_doc}")

            base_img = 0
            plantilla = R.ruta_del_proyecto(cfg["plantilla_docx"]) if cfg.get("plantilla_docx") else None
            if plantilla and plantilla.exists():
                base_img = len(R.Document(str(plantilla)).inline_shapes)
            img_doc = len(doc.inline_shapes) - base_img
            rotas = [t for t in textos if R.IMAGEN_FALTANTE in t]
            check("imágenes del borrador en el documento", img_doc == imagenes_md and not rotas,
                  f"esperadas={imagenes_md} documento={img_doc} no encontradas={len(rotas)}", rotas)

            if pat:
                cp = doc.core_properties
                props = [f"{k}: {getattr(cp, k)}" for k in ("title", "subject", "author", "keywords", "comments",
                                                            "last_modified_by", "category") if getattr(cp, k)]
                hd = buscar_huella(pat, textos + props)
                check("D1 documento: sin huella en el texto ni en las propiedades", not hd, f"párrafos={len(hd)}",
                      [f"«{t}» en: {s[:100]}" for _, t, s in hd])

    print(f"RESULTADO: {'CONFORME' if not fallas else f'NO CONFORME ({fallas} falla(s))'}")
    return 0 if not fallas else 1


if __name__ == "__main__":
    sys.exit(main())
